//! Renders the Markdown report from raw result lines. Every sentence that states a comparison is
//! computed from the records; nothing here is written for a particular outcome.

mod sections;
mod table;

use crate::record::{EngineInfo, Failure, Line, Record, SyncPrimitive};
use crate::sysinfo::Host;

pub use table::{count, duration_us, mib, param_str, param_u64, ratio, Table};

/// Engines whose results describe LiliaDB itself (excluded from "best competitor").
#[must_use]
pub fn is_lilia(id: &str) -> bool {
    id == "lilia" || id.starts_with("lilia-")
}

/// Everything the sections read.
pub struct Data<'a> {
    pub host: Option<&'a Host>,
    pub records: Vec<&'a Record>,
    pub failures: Vec<&'a Failure>,
}

impl<'a> Data<'a> {
    fn new(lines: &'a [Line]) -> Self {
        let mut data = Self { host: None, records: Vec::new(), failures: Vec::new() };
        for line in lines {
            match line {
                Line::Host(host) => data.host = Some(host),
                Line::Record(record) => data.records.push(record),
                Line::Failure(failure) => data.failures.push(failure),
            }
        }
        data
    }

    #[must_use]
    pub fn os(&self) -> &str {
        self.host.map_or(std::env::consts::OS, |h| h.os.as_str())
    }

    /// `power-safe`, `drive cache` or `no sync`, for the OS the results were measured on.
    #[must_use]
    pub fn class(&self, info: &EngineInfo) -> &'static str {
        if info.sync.power_safe_on(self.os()) {
            "power-safe"
        } else if info.sync == SyncPrimitive::None {
            "no sync"
        } else {
            "drive cache"
        }
    }

    /// Whether the single-commit latency `p50_us` of `info` is consistent with its declared sync.
    /// Only a power-safe commit on Apple platforms has a physical lower bound (one drive-cache
    /// flush, about 4 ms); a slow drive-cache commit proves nothing about its sync.
    #[must_use]
    pub fn sync_check(&self, info: &EngineInfo, p50_us: Option<f64>) -> &'static str {
        let apple = matches!(self.os(), "macos" | "ios");
        match (apple, self.class(info), p50_us) {
            (true, "power-safe", Some(p)) if p < 1_000.0 => "⚠ faster than a drive-cache flush: declared sync not observed",
            (true, "power-safe", Some(_)) => "at least one flush per commit",
            (_, _, Some(_)) => "not verifiable from latency",
            (_, _, None) => "not measured",
        }
    }

    /// Records of `suite`/`workload` accepted by `keep`.
    pub fn select(&self, suite: &str, workload: &str, keep: impl Fn(&Record) -> bool) -> Vec<&'a Record> {
        self.records.iter().copied().filter(|r| r.suite == suite && r.workload == workload && keep(r)).collect()
    }

    /// Distinct engines among `records`, in first-appearance order.
    #[must_use]
    pub fn engines(records: &[&'a Record]) -> Vec<&'a EngineInfo> {
        let mut seen: Vec<&EngineInfo> = Vec::new();
        for r in records {
            if !seen.iter().any(|e| e.id == r.engine.id && e.name == r.engine.name) {
                seen.push(&r.engine);
            }
        }
        seen
    }
}

/// Selects the record of one pivot column.
pub type Column = Box<dyn Fn(&Record) -> bool>;

/// One pivot row: an engine and its record in each column.
pub type Row<'a> = (&'a EngineInfo, Vec<Option<&'a Record>>);

/// Wraps a predicate as a pivot column.
pub fn column(keep: impl Fn(&Record) -> bool + 'static) -> Column {
    Box::new(keep)
}

/// Rows of a pivot: one per engine, one optional record per column, sorted by the first
/// column's throughput, highest first.
pub fn pivot<'a>(records: &[&'a Record], columns: &[Column]) -> Vec<Row<'a>> {
    let mut rows: Vec<Row<'a>> = Data::engines(records)
        .into_iter()
        .map(|engine| {
            let cells = columns
                .iter()
                .map(|keep| {
                    records.iter().copied().find(|r| r.engine.id == engine.id && r.engine.name == engine.name && keep(r))
                })
                .collect();
            (engine, cells)
        })
        .collect();
    rows.sort_by(|a, b| {
        let key = |row: &Row<'_>| row.1.iter().flatten().next().map_or(-1.0, |r| r.ops_per_sec);
        key(b).total_cmp(&key(a))
    });
    rows
}

/// Engine name in tables, LiliaDB rows in bold.
#[must_use]
pub fn label(engine: &EngineInfo) -> String {
    if is_lilia(&engine.id) {
        format!("**{}**", engine.name)
    } else {
        engine.name.clone()
    }
}

#[must_use]
pub fn render(lines: &[Line], source: &str) -> String {
    let data = Data::new(lines);
    let mut out = String::new();
    out.push_str("# LiliaDB benchmarks\n\n");
    out.push_str(&format!(
        "> Generated by `tools/lilia-bench` from [`{source}`]({}). Do not edit by hand: \
         run `pnpm bench:compare` to measure again, or `lilia-bench render` to rebuild this page \
         from the raw results.\n\n",
        source.strip_prefix("docs/").unwrap_or(source)
    ));
    for section in [
        sections::environment,
        sections::engines,
        sections::summary,
        sections::writes,
        sections::reads,
        sections::ycsb,
        sections::json,
        sections::fts,
        sections::vectors,
        sections::analytics,
        sections::sdk,
        sections::failures,
        sections::method,
    ] {
        let text = section(&data);
        if !text.is_empty() {
            out.push_str(&text);
            out.push('\n');
        }
    }
    out
}
